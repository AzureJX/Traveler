class Mine:
    def __init__(self, planet, max):
        self.planet = planet
        self.mineButton = Button(185, 630, 210, 35, 17, f'MINE THE {self.planet}')
        self.mine = False
        self.mined = False
        self.mineProgress = 0
        self.fuelGain = 0
        self.mTimer = 0
        self.display = True
        self.display_2 = True
        self.noMineAgain = False
        self.max = max
    
    def draw(self):
        drawImage(CMUImage(Image.open('images/mine.png')),
                  50, 400, width = 270, height = 200)
        self.mineButton.draw()
        if self.mine and 0 < self.mineProgress < 100:
            drawRect(85, 370, self.mineProgress * 2, 11, fill = 'gold')
            drawRect(83, 368, 204, 15, fill = None, border = 'cornflowerBlue', borderWidth = 3)
        elif self.mineProgress >= 100:
            if self.display:
                drawLabel(f'You mined {self.fuelGain} percent of fuel!', 400, 50,
                          size = 22, font = 'orbitron', fill='white', bold=True)
        if self.noMineAgain:
            if self.display_2:
                drawLabel('You can only mine once', 400, 100, 
                          size = 20, font = 'orbitron', bold=True, fill='white')

    def buttonControl(self, mouseX, mouseY):
        if self.mineButton.clickOn(mouseX, mouseY) and not self.mined:
            self.mine = True
        elif self.mineButton.clickOn(mouseX, mouseY) and self.mined:
            self.noMineAgain = True
            self.display_2 = True
    
    def takeMineStep(self, app): 
        if not self.mined and self.mine and self.mineProgress < 100: # mining process
            self.mineProgress += 1
        elif not self.mined and self.mine and self.mineProgress >= 100:
            self.mine = False
            self.mined = True
            self.fuelGain = random.randint(15, self.max) # may change
            if app.fuel + self.fuelGain >= 100:
                app.fuel = 100
            else:
                app.fuel += self.fuelGain
        if self.mineProgress >= 100: # display how much you mine
            self.mTimer += 1
            if self.mTimer >= 50:
                self.display = False
                self.mTimer = 0
                self.mineProgress = 0
        if self.noMineAgain: # display don't mine again
            self.mTimer += 1
            if self.mTimer >= 50:
                self.display_2 = False
                self.mTimer = 0
                self.noMineAgain = False

class QA:
    def __init__(self):
        self.correct = 0 # total correct
        self.total = 0 # total answered
        self.button0 = None
        self.button1 = None
        self.button2 = None
        self.questions = dict()
        self.question = None
        self.star = None
    
    def generateQA(self):
        self.question = random.choice(list(self.questions.keys()))
        answers = self.questions[self.question]
        self.button0 = Button(600, 400, 200, 40, 16, answers[0])
        self.button1 = Button(600, 550, 200, 40, 16, answers[1])
        if len(answers) > 3:
            self.button2 = Button(600, 475, 200, 40, 16, answers[2])
        self.total += 1
    
    def QAdraw(self):
        drawLabel(self.question, 400, 100, size = 20, fill='white', bold=True, font='orbitron')
        drawRect(400, 130, 700, 10, fill='cornSilk', align='center')
        drawPolygon(220, 130, 240, 130, 230, 185, fill='cornSilk')
        if self.button0 != None:
            self.button0.draw()
            self.button1.draw()
        if self.button2 != None:
            self.button2.draw()
    
    def mouseControl(self, mx, my, app):
        if self.button0.clickOn(mx, my):
            self.check(self.button0, app)
        elif self.button1.clickOn(mx, my):
            self.check(self.button1, app)
        elif self.button2 != None and self.button2.clickOn(mx, my):
            self.check(self.button2, app)

    def check(self, button, app):
        if self.isCorrect(button):
            self.correct += 1
            app.jewels += 100
            self.button2 = None
        else:
            self.button2 = None
        if self.total < 3:
            self.questions.pop(self.question)
            self.generateQA()
        else:
            setActiveScreen(self.star + 'End')
    
    def isCorrect(self, button):
        correctIndex = self.questions[self.question][-1]
        if button == self.questions[self.question][correctIndex]:
            return True
        return False

    def endDraw(self):
        if self.correct == 0:
            drawLabel('You got it all wrong!', 400, 80, size = 35, fill='white', font='orbitron')
            drawLabel('Go back to your ship.', 400, 130, size = 35, fill='white', font='orbitron')
        elif self.correct == 1:
            drawLabel('You only got one right.', 400, 80, size = 35, fill='white', font='orbitron')
            drawLabel("Here's 100 pounds of jewels for you.", 400, 130, size = 35, fill='white', font='orbitron')
        elif self.correct == 2:
            drawLabel('You got two right.', 400, 80, size = 35, fill='white', font='orbitron')
            drawLabel("Here's 200 pounds of jewels for you.", 400, 130, size = 35, fill='white', font='orbitron')
        elif self.correct == 3:
            drawLabel('You got it all right!', 400, 80, size = 35, fill='white', font='orbitron')
            drawLabel("Here's 300 pounds of jewels for you.", 400, 130, size = 35, fill='white', font='orbitron')

