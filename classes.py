def vec(x, y):
    return np.array([x, y])

class Object:
    def __init__(self, d, v):
        self.d = d
        self.f = vec(0, 0)
        self.v = v

class Black_Hole(Object):
    def __init__(self, d, v, r, image):
        super().__init__(d, v)
        self.MRratio = 10000/3
        self.LRratio = 0.5
        self.image = image
        self.r = r
        self.m = self.r * self.MRratio
        self.limit = self.r + 50 # * (1 + self.LRratio)
        self.angle = 0

    def draw(self):
        x, y = self.d
        drawImage(self.image, float(x), float(y), align = 'center', 
                  width = self.r * 2, height = self.r * 2, rotateAngle = self.angle)

    def simpleDraw(self): # test
        x, y = self.d
        drawCircle(float(x), float(y), self.r)
        endX = float(x) + self.r*math.cos(math.radians(self.angle))
        endY = float(y) + self.r*math.sin(math.radians(self.angle))
        drawLine(float(x), float(y), endX, endY, fill='red', lineWidth = 4) # to show the rotation
    
    def __deepcopy__(self, memo): # This method is generated by ChatGPT
        # Create a new Black_Hole instance with deep-copied attributes
        new_black_hole = Black_Hole(
            copy.deepcopy(self.d, memo),
            copy.deepcopy(self.v, memo),
            self.r,
            self.image  # Skip deep-copying the image
        )
        new_black_hole.MRratio = self.MRratio
        new_black_hole.LRratio = self.LRratio
        new_black_hole.limit = self.limit
        new_black_hole.angle = self.angle
        return new_black_hole
    
