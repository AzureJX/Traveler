class Button:
    def __init__(self, cx, cy, w, h, size = 20, text = None): # may have image
        self.cx = cx
        self.cy = cy
        self.w = w
        self.h = h
        self.text = text
        self.image = CMUImage(Image.open('images/button.png'))
        self.size = size
    
    def draw(self):
        drawImage(self.image, self.cx, self.cy, width = self.w, height = self.h, align = 'center')
        if self.text != None:
            drawLabel(self.text, self.cx, self.cy, size = self.size, font = 'orbitron')
    
    def clickOn(self, mouseX, mouseY):
        if (abs(mouseX - self.cx) < self.w/2) and (abs(mouseY - self.cy) < self.h/2):
            return True
        return False

    def __eq__(self, other):
        if self.text == other:
            return True
        return False

